export function t(key: string, lang: LanguageCode = 'en'): string {
  const dict = translations[lang] || translations.en;
  return dict[key] || translations.en[key] || key;
}

// Speech synthesis narrator utility
export function speakText(text: string, lang: LanguageCode, onEnd?: () => void) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    if (onEnd) onEnd();
    return;
  }

  window.speechSynthesis.cancel();

  const langCodeMap: Record<LanguageCode, string> = {
    en: 'en-IN',
    hi: 'hi-IN',
    kn: 'kn-IN',
    te: 'te-IN',
    ta: 'ta-IN',
    ml: 'ml-IN',
    mr: 'mr-IN',
    bn: 'bn-IN'
  };

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = langCodeMap[lang] || 'en-IN';
  utterance.rate = 0.9; // Clear, easy pace for young students
  utterance.pitch = 1.05;

  if (onEnd) {
    utterance.onend = onEnd;
    utterance.onerror = onEnd;
  }

  window.speechSynthesis.speak(utterance);
}

export function stopSpeaking() {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.cancel();
  }
}
